import { readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";
import { loginNurse, manifest } from "./local-accounts";
const evidence = JSON.parse(readFileSync(new URL("../../SynCare-be/data/m04-live-evidence.json", import.meta.url), "utf8")) as { reports: { id: string; patientId: string; outcome: { action: string } }[] };
const urgent = evidence.reports.find(r => r.outcome.action === "escalate_immediately")!;
test.use({ trace: "off" });
test("monitoring_keyboard_detail: actual assigned latest/history, urgent guidance information only and no cross-patient response", async ({ page, context }, testInfo) => {
  test.setTimeout(90000);
  await loginNurse(page);
  await page.getByRole("navigation").getByRole("link", { name: "Pemantauan", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Pemantauan pasien", exact: true })).toBeVisible();
  const response = await context.request.get("/api/syncare/v1/monitoring?limit=20");
  expect(response.status()).toBe(200);
  const rows = (await response.json()).data;
  expect(rows.some((r: { id: string }) => r.id === manifest.patients[1]!.patientId)).toBe(false);
  const patientLink = page.locator(`a[href="/monitoring/patients/${urgent.patientId}"]`);
  await expect(patientLink).toBeVisible(); await patientLink.focus(); await patientLink.press("Enter");
  await expect(page.getByRole("heading", { name: "Riwayat laporan pasien", exact: true })).toBeVisible();
  const link = page.locator(`a[href="/monitoring/reports/${urgent.id}"]`);
  await expect(link).toBeVisible(); await link.focus(); await expect(link).toBeFocused(); await link.press("Enter");
  await expect(page).toHaveURL(new RegExp(`/monitoring/reports/${urgent.id}$`), { timeout: 30000 });
  await expect(page.getByRole("region", { name: "Peringatan mendesak" })).toContainText("Ini tidak berarti bantuan dikirim");
  await expect(page.getByText("Demo hanya menampilkan informasi; tidak melakukan panggilan.")).toBeVisible();
  await expect(page.getByText(/Darurat medis Indonesia.*119/)).toBeVisible();
  await expect(page.locator('a[href^="tel:"]')).toHaveCount(0);
  const foreign = evidence.reports.find(r => r.patientId === manifest.patients[1]!.patientId)!;
  expect((await context.request.get(`/api/syncare/v1/checkins/${foreign.id}`)).status()).toBe(404);
  await page.getByRole("region", { name: "Peringatan mendesak" }).screenshot({ path: testInfo.outputPath("m04-urgent-desktop.png") });
  await page.setViewportSize({ width: 320, height: 800 });
  await page.evaluate(() => { document.documentElement.style.fontSize = "200%"; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  expect(await page.getByRole("heading", { name: "Peringatan mendesak dari F2" }).evaluate(heading => {
    const range = document.createRange();
    range.setStart(heading.firstChild!, 0); range.setEnd(heading.firstChild!, "Peringatan".length);
    return range.getClientRects().length;
  })).toBe(1);
  await page.screenshot({ path: testInfo.outputPath("m04-urgent-320-text200.png"), fullPage: true });
  await page.getByRole("heading", { name: "Peringatan mendesak dari F2" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("m04-urgent-320-viewport.png") });
  await page.getByText("Demo hanya menampilkan informasi; tidak melakukan panggilan.").scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("m04-guidance-320-viewport.png") });
  await page.getByRole("link", { name: "Riwayat pasien ini" }).click();
  await expect(page.getByRole("heading", { name: "Riwayat laporan pasien", exact: true })).toBeVisible();
  await expect(page.getByRole("listitem").filter({ has: page.locator(`a[href="/monitoring/reports/${urgent.id}"]`) }).getByText("Peringatan mendesak dari F2")).toBeVisible();
});
test("monitoring failed refresh preserves allowed content; revoked/not-found detail clears private message", async ({ page, context }) => {
  await loginNurse(page); await page.goto(`/monitoring/reports/${urgent.id}`);
  await expect(page.getByRole("article", { name: "Detail laporan pasien" })).toBeVisible();
  const latest = (await (await context.request.get(`/api/syncare/v1/checkins/${urgent.id}`)).json()).data;
  await page.route(`**/api/syncare/v1/checkins/${urgent.id}`, route => route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ data: { ...latest, processing: { ...latest.processing, state: "FAILED", failureCode: "dependency_unavailable" }, outcome: null, alertEvidence: "not_applicable" }, requestId: "synthetic-analysis-failure" }) }));
  await page.getByRole("button", { name: "Muat ulang status laporan" }).click();
  await expect(page.getByText("Analisis belum berhasil", { exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Peringatan mendesak" })).toHaveCount(0);
  await page.unroute(`**/api/syncare/v1/checkins/${urgent.id}`);
  await page.route(`**/api/syncare/v1/checkins/${urgent.id}`, route => route.abort());
  await page.getByRole("button", { name: "Muat ulang status laporan" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Layanan belum tersedia" })).toBeVisible();
  await expect(page.getByText(latest.message, { exact: true })).toBeVisible();
  await page.unroute(`**/api/syncare/v1/checkins/${urgent.id}`);
  await page.route(`**/api/syncare/v1/checkins/${urgent.id}`, route => route.fulfill({ status: 404, contentType: "application/json", body: JSON.stringify({ error: { code: "not_found", message: "Data tidak ditemukan.", requestId: "unit-revoked", retryable: false } }) }));
  await page.getByRole("button", { name: "Muat ulang status laporan" }).click();
  await expect(page.getByText(latest.message, { exact: true })).toHaveCount(0);
  await expect(page.getByRole("alert").filter({ hasText: "Data tidak ditemukan" })).toBeVisible();
});

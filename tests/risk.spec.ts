import { expect, test } from "@playwright/test";
import { loginNurse, mutationHeaders, syntheticSource, targetPatient } from "./local-accounts";

test.use({ trace: "off" });
test("risk_ui_distinguishes_proposed_confirmed: actual F1 v1/v2, held pending request, Q03 and stale confirmation refetch", async ({ page, context }, testInfo) => {
  test.setTimeout(180000);
  await loginNurse(page);
  await page.goto(`/patients/${targetPatient}`);
  await expect(page.getByLabel("Teks ringkasan pulang")).toBeVisible();
  const before = (await (await context.request.get(`/api/syncare/v1/patients/${targetPatient}/overview`)).json()).data;
  const firstVersion = (before.currentDischarge?.version ?? 0) + 1;
  await page.getByLabel("Teks ringkasan pulang").fill(syntheticSource);
  await page.getByRole("button", { name: "Simpan versi baru", exact: true }).click();
  await expect(page.getByText(`Sumber aktif: versi ${firstVersion}.`, { exact: false })).toBeVisible();
  await expect(page.getByRole("button", { name: "Jalankan penilaian F1" })).toBeEnabled();
  let release!: () => void;
  const hold = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/api/syncare/v1/discharges/*/assessments", async route => { await hold; await route.continue(); }, { times: 1 });
  const response1 = page.waitForResponse(response => response.request().method() === "POST" && /\/discharges\/.+\/assessments$/.test(response.url()));
  await page.getByRole("button", { name: "Jalankan penilaian F1" }).click();
  await expect(page.getByRole("button", { name: "Menilai sumber...", exact: true })).toBeDisabled();
  release();
  const first = (await (await response1).json()).data;
  expect(first.state).toBe("SUCCEEDED");
  expect(["LOW", "MEDIUM", "HIGH"]).toContain(first.output.tier);
  await expect(page.getByRole("button", { name: `Konfirmasi kategori ${first.output.tier}`, exact: true })).toBeEnabled();
  const risk = page.getByRole("region", { name: "Kategori risiko pasien" });
  await expect(risk).not.toContainText("Kategori dikonfirmasi:");
  await page.getByRole("button", { name: `Konfirmasi kategori ${first.output.tier}`, exact: true }).click();
  await expect(risk).toContainText(`Kategori dikonfirmasi: ${first.output.tier}`);
  await page.getByLabel("Teks ringkasan pulang").fill(`${syntheticSource}\nVersi sumber diperbarui untuk uji konfirmasi ulang.`);
  await page.getByRole("button", { name: "Simpan versi baru", exact: true }).click();
  await expect(risk).toContainText("Perlu penilaian dan konfirmasi ulang");
  await expect(risk).toContainText(`Kategori sebelumnya: ${first.output.tier}`);
  await expect(page.getByRole("button", { name: /^Konfirmasi kategori/ })).toHaveCount(0);
  const response2 = page.waitForResponse(response => response.request().method() === "POST" && /\/discharges\/.+\/assessments$/.test(response.url()));
  await page.getByRole("button", { name: "Jalankan penilaian F1" }).click();
  const second = (await (await response2).json()).data;
  expect(second.state).toBe("SUCCEEDED");
  expect(second.sourceVersion).toBe(firstVersion + 1);
  await expect(page.getByRole("button", { name: `Konfirmasi kategori ${second.output.tier}`, exact: true })).toBeEnabled();
  await expect(risk).toContainText("Perlu penilaian dan konfirmasi ulang");
  const parallel = await context.request.post(`/api/syncare/v1/assessments/${second.id}/confirmations`, {
    headers: await mutationHeaders(context.request), data: { category: second.output.tier, expectedVersion: second.version },
  });
  expect(parallel.status()).toBe(201);
  await page.getByRole("button", { name: `Konfirmasi kategori ${second.output.tier}`, exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Data berubah. Data terbaru dimuat" })).toBeVisible();
  await expect(risk).toContainText(`Kategori dikonfirmasi: ${second.output.tier}`);
  await expect(page.getByRole("button", { name: `Konfirmasi kategori ${second.output.tier}`, exact: true })).toBeDisabled();
  const history = (await (await context.request.get(`/api/syncare/v1/patients/${targetPatient}/assessments`)).json()).confirmations;
  expect(history.filter((c: { assessmentId: string }) => c.assessmentId === second.id)).toHaveLength(1);
  expect(history.some((c: { assessmentId: string; applicable: boolean }) => c.assessmentId === first.id && !c.applicable)).toBe(true);
  await page.setViewportSize({ width: 320, height: 800 });
  await page.evaluate(() => { document.documentElement.style.fontSize = "200%"; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.getByLabel("Teks ringkasan pulang").focus();
  expect(await page.getByLabel("Teks ringkasan pulang").evaluate(input => getComputedStyle(input).outlineStyle)).toBe("solid");
  await page.screenshot({ path: testInfo.outputPath("m03-risk-320-text200.png"), fullPage: true });
  await risk.screenshot({ path: testInfo.outputPath("m03-confirmed-risk.png") });
});
